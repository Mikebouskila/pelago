const RARITY_ORDER = { legendary: 0, epic: 1, rare: 2, common: 3 };

const relicCache = new Map();
function relicsOf(project) {
  if (!relicCache.has(project.id)) {
    relicCache.set(project.id, RELICS
      .map((relic) => ({ relic, reason: relic.test(project) }))
      .filter((entry) => entry.reason)
      .sort((a, b) => RARITY_ORDER[a.relic.rarity] - RARITY_ORDER[b.relic.rarity]));
  }
  return relicCache.get(project.id);
}

function paintSprite(name, plot) {
  const sprite = RELIC_SPRITES[name];
  if (!sprite) return { width: 0, height: 0 };
  const colours = {};
  Object.entries(sprite.palette).forEach(([key, hex]) => { colours[key] = hexRgb(hex); });
  const height = sprite.rows.length;
  sprite.rows.forEach((row, y) => [...row].forEach((char, x) => { if (char !== '.' && colours[char]) plot(x, y, colours[char]); }));
  return { width: sprite.rows[0].length, height };
}

// A crisp icon canvas for the interface.
function relicIcon(name, scale = 4, locked = false) {
  const sprite = RELIC_SPRITES[name];
  const canvas = document.createElement('canvas');
  canvas.width = Math.max(...sprite.rows.map((row) => row.length)) * scale; canvas.height = sprite.rows.length * scale;
  const context = canvas.getContext('2d');
  paintSprite(name, (x, y, colour) => {
    context.fillStyle = locked ? '#2a3550' : `rgb(${colour[0]},${colour[1]},${colour[2]})`;
    context.fillRect(x * scale, y * scale, scale, scale);
  });
  canvas.className = 'relic-icon';
  canvas.setAttribute('aria-hidden', 'true');
  return canvas;
}

